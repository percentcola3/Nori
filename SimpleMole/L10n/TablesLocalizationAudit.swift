    /// Only known Nori catalog labels are translated. Application names and
    /// directory names originating from users remain verbatim.
    static func categoryName(_ name: String, isAppLeftover: Bool = false) -> String {
        if isAppLeftover, name.hasSuffix(" leftovers") {
            return L10n.shared.tf("audit.category.leftovers", String(name.dropLast(" leftovers".count)))
        }
        for browser in browserNames where name.hasPrefix(browser + " ") {
            let leaf = String(name.dropFirst(browser.count + 1))
            if let key = browserLeafKeys[leaf] { return L10n.shared.tf(key, browser) }
        }
        guard let key = categoryKeys[name] else { return name }
        return L10n.shared.t(key)
    }

